-- Esquema de la API bancaria (datos 100 % ficticios).
-- Importes: NUMERIC(19,2). Nunca se usa coma flotante para dinero.

CREATE TABLE customers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL,
    phone       VARCHAR(25)  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_customers_email UNIQUE (email),
    CONSTRAINT ck_customers_status CHECK (status IN ('ACTIVE', 'BLOCKED'))
);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(160) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    customer_id   BIGINT REFERENCES customers (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_customer UNIQUE (customer_id),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'OPERATOR', 'ADMIN')),
    -- Solo los usuarios CUSTOMER están vinculados a un cliente.
    CONSTRAINT ck_users_customer CHECK ((role = 'CUSTOMER') = (customer_id IS NOT NULL))
);

CREATE TABLE accounts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT       NOT NULL REFERENCES customers (id),
    number      VARCHAR(20)  NOT NULL,
    type        VARCHAR(20)  NOT NULL,
    currency    VARCHAR(3)   NOT NULL,
    balance     NUMERIC(19, 2) NOT NULL DEFAULT 0,
    status      VARCHAR(20)  NOT NULL,
    opened_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_accounts_number UNIQUE (number),
    CONSTRAINT ck_accounts_balance CHECK (balance >= 0),
    CONSTRAINT ck_accounts_type CHECK (type IN ('SAVINGS', 'CHECKING')),
    CONSTRAINT ck_accounts_currency CHECK (currency IN ('MXN', 'USD', 'EUR')),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'CLOSED'))
);
CREATE INDEX ix_accounts_customer ON accounts (customer_id);

-- Historial inmutable: la aplicación solo inserta filas (nunca UPDATE ni DELETE).
CREATE TABLE transactions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference              VARCHAR(30)    NOT NULL,
    type                   VARCHAR(20)    NOT NULL,
    status                 VARCHAR(20)    NOT NULL,
    amount                 NUMERIC(19, 2) NOT NULL,
    currency               VARCHAR(3)     NOT NULL,
    source_account_id      BIGINT REFERENCES accounts (id),
    destination_account_id BIGINT REFERENCES accounts (id),
    source_balance_after   NUMERIC(19, 2),
    destination_balance_after NUMERIC(19, 2),
    description            VARCHAR(140),
    failure_code           VARCHAR(40),
    failure_reason         VARCHAR(255),
    initiated_by           BIGINT         NOT NULL REFERENCES users (id),
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_transactions_reference UNIQUE (reference),
    CONSTRAINT ck_transactions_amount CHECK (amount > 0),
    CONSTRAINT ck_transactions_type CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT ck_transactions_status CHECK (status IN ('COMPLETED', 'REJECTED')),
    CONSTRAINT ck_transactions_accounts CHECK (
        (type = 'DEPOSIT'    AND destination_account_id IS NOT NULL AND source_account_id IS NULL) OR
        (type = 'WITHDRAWAL' AND source_account_id IS NOT NULL AND destination_account_id IS NULL) OR
        (type = 'TRANSFER'   AND source_account_id IS NOT NULL AND destination_account_id IS NOT NULL))
);
CREATE INDEX ix_transactions_source ON transactions (source_account_id, created_at);
CREATE INDEX ix_transactions_destination ON transactions (destination_account_id, created_at);

CREATE TABLE idempotency_keys (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idem_key              VARCHAR(100) NOT NULL,
    user_id               BIGINT       NOT NULL REFERENCES users (id),
    request_hash          VARCHAR(64)  NOT NULL,
    response_status       INTEGER      NOT NULL,
    transaction_reference VARCHAR(30)  NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    -- La clave es única por usuario: dos usuarios pueden generar el mismo UUID sin interferir.
    CONSTRAINT uk_idempotency_user_key UNIQUE (user_id, idem_key)
);
CREATE INDEX ix_idempotency_expires ON idempotency_keys (expires_at);

CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor       VARCHAR(160) NOT NULL,
    action      VARCHAR(40)  NOT NULL,
    resource    VARCHAR(80),
    result      VARCHAR(20)  NOT NULL,
    detail      VARCHAR(255),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_created ON audit_events (created_at);
